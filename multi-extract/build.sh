#!/usr/bin/env bash
# Builds b1tw153-multiregion.yml from compose.template.yml and the scripts in
# sidecar/. Each "@@INCLUDE <file>@@" line is replaced by that file, indented to
# the marker's column, with every $ doubled (Compose interpolates $ everywhere
# in the file, including configs content).
#
# Usage: ./build.sh           write b1tw153-multiregion.yml
#        ./build.sh --check   fail if b1tw153-multiregion.yml is out of date
set -euo pipefail
cd "$(dirname "$0")"
OUT=b1tw153-multiregion.yml

build() {
  echo "# GENERATED by build.sh from compose.template.yml and sidecar/. Edit those, then run ./build.sh."
  local line indent file
  while IFS= read -r line || [ -n "$line" ]; do
    if [[ $line =~ ^([[:space:]]*)@@INCLUDE\ ([^@]+)@@[[:space:]]*$ ]]; then
      indent=${BASH_REMATCH[1]} file=${BASH_REMATCH[2]}
      [ -f "$file" ] || { echo "build.sh: $file not found" >&2; return 1; }
      sed -e 's/\$/$$/g' -e "s/^/$indent/" -e 's/^[[:space:]]*$//' "$file"
    else
      printf '%s\n' "$line"
    fi
  done <compose.template.yml
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
build >"$tmp"
# Check it parses, with placeholder region lists.
OSM_EXTRACT_URLS=x OSM_DIFF_URLS=x docker compose -f "$tmp" --project-directory . config -q

if [ "${1:-}" = --check ]; then
  diff -u "$OUT" "$tmp" && echo "$OUT is up to date"
else
  cp "$tmp" "$OUT"
  echo "wrote $OUT"
fi
